function readInitialSource() {
  if (typeof window === 'undefined') {
    return templates[0].source
  }

  return window.localStorage.getItem(STORAGE_KEY) ?? templates[0].source
}

function downloadBlob(data: Uint8Array, filename: string, type: string) {
  const copy = new Uint8Array(data)
  const blob = new Blob([copy.buffer], { type })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  link.click()
  URL.revokeObjectURL(url)
}

export default function App() {
  const [source, setSource] = useState(readInitialSource)
  const [preview, setPreview] = useState('')
  const [status, setStatus] = useState('Loading Typst WASM')
  const [error, setError] = useState('')
  const [isCompiling, setIsCompiling] = useState(false)
  const [isExporting, setIsExporting] = useState(false)
  const [isDragging, setIsDragging] = useState(false)
  const [documentName, setDocumentName] = useState('studio-draft.typ')
  const fileInputRef = useRef<HTMLInputElement>(null)

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, source)
    const timeout = window.setTimeout(async () => {
      setIsCompiling(true)
      setStatus('Compiling preview')
      setError('')

      try {
        const svg = await renderTypstSvg(source)
        setPreview(svg)
        setStatus('Preview ready')
      } catch (caught) {
        setPreview('')
        setError(caught instanceof Error ? caught.message : String(caught))
        setStatus('Compile failed')
      } finally {
        setIsCompiling(false)
      }
    }, 420)

    return () => window.clearTimeout(timeout)
  }, [source])

  async function loadFile(file: File) {
    if (!file.name.endsWith('.typ')) {
      setError('Choose a .typ file.')
      return
    }

    setDocumentName(file.name)
    setSource(await file.text())
    setStatus('Loaded local file')
  }

  async function handleExport() {
    setIsExporting(true)
    setError('')

    try {
      const pdf = await exportTypstPdf(source)
      downloadBlob(pdf, documentName.replace(/\.typ$/i, '.pdf'), 'application/pdf')
      setStatus('PDF exported')
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : String(caught))
      setStatus('Export failed')
    } finally {
      setIsExporting(false)
    }
  }

  return (
    <main
      className="grid min-h-svh grid-rows-[auto_1fr] bg-background text-foreground"
      onDragOver={(event) => {
        event.preventDefault()
        setIsDragging(true)
      }}
      onDragLeave={() => setIsDragging(false)}
      onDrop={(event) => {
        event.preventDefault()
        setIsDragging(false)
        const file = event.dataTransfer.files.item(0)
        if (file) {
          void loadFile(file)
        }
      }}
    >
      <header className="flex min-h-16 items-center justify-between border-b border-border bg-panel px-4">
        <div className="flex min-w-0 items-center gap-3">
          <div className="flex size-9 shrink-0 items-center justify-center rounded-md bg-primary text-primary-foreground">
            <FileText className="size-5" aria-hidden="true" />
          </div>
          <div className="min-w-0">
            <h1 className="truncate text-base font-semibold leading-5">
              Typst Studio
            </h1>
            <p className="truncate text-xs text-muted-foreground">
              {documentName}
            </p>
          </div>
        </div>
        <div className="hidden items-center gap-2 lg:flex">
          <Badge className="gap-1.5">
            <Lock className="size-3.5" aria-hidden="true" />
            browser only
          </Badge>
          <Badge className="gap-1.5">
            <HardDrive className="size-3.5" aria-hidden="true" />
            cached WASM
          </Badge>
          <Badge className="gap-1.5">
            <ShieldCheck className="size-3.5" aria-hidden="true" />
            no server compile
          </Badge>
        </div>
        <div className="flex items-center gap-2">
          <Button
            type="button"
            variant="outline"
            onClick={() => fileInputRef.current?.click()}
          >
            <FolderOpen aria-hidden="true" />
            <span className="hidden sm:inline">Open</span>
          </Button>
          <Button type="button" onClick={handleExport} disabled={isExporting}>
            <Download aria-hidden="true" />
            <span className="hidden sm:inline">
              {isExporting ? 'Exporting' : 'Export PDF'}
            </span>
          </Button>
          <input
            ref={fileInputRef}
            className="hidden"
            type="file"
            accept=".typ,text/*"
            onChange={(event) => {
              const file = event.target.files?.[0]
              if (file) {
                void loadFile(file)
              }
              event.currentTarget.value = ''
            }}
          />
        </div>
      </header>

      <section className="grid min-h-0 grid-cols-1 lg:grid-cols-[minmax(380px,0.92fr)_minmax(480px,1.08fr)]">
        <aside className="grid min-h-0 grid-rows-[auto_auto_1fr] border-b border-border bg-sidebar lg:border-b-0 lg:border-r">
          <div className="border-b border-border p-3">
            <div className="grid grid-cols-3 gap-2">
              {templates.map((template) => (
                <button
                  key={template.name}
                  type="button"
                  className="rounded-md border border-border bg-background p-3 text-left transition-colors hover:bg-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
                  onClick={() => {
                    setDocumentName(`${template.name.toLowerCase()}.typ`)
                    setSource(template.source)
                  }}
                >
                  <span className="block text-sm font-medium">
                    {template.name}
                  </span>
                  <span className="mt-1 block text-xs leading-4 text-muted-foreground">
                    {template.description}
                  </span>
                </button>
              ))}
            </div>
          </div>

          <div className="flex items-center justify-between border-b border-border px-3 py-2 text-xs text-muted-foreground">
            <span className="inline-flex items-center gap-1.5">
              <Gauge className="size-3.5" aria-hidden="true" />
              {status}
            </span>
            <span>{source.length.toLocaleString()} chars</span>
          </div>

          <div className="min-h-0 p-3">
            <Textarea
              value={source}
              onChange={(event) => setSource(event.target.value)}
              spellCheck={false}
              className="h-full min-h-[52svh] lg:min-h-0"
              aria-label="Typst source"
            />
          </div>
        </aside>

        <section className="relative min-h-[58svh] overflow-hidden bg-preview">
          <div className="flex h-11 items-center justify-between border-b border-border bg-panel px-3">
            <div className="flex items-center gap-2 text-sm font-medium">
              <Play
                className={isCompiling ? 'size-4 animate-pulse' : 'size-4'}
                aria-hidden="true"
              />
              Live preview
            </div>
            <Badge className="gap-1.5">
              <Sparkles className="size-3.5" aria-hidden="true" />
              Typst WASM
            </Badge>
          </div>

          <div className="h-[calc(100%-2.75rem)] overflow-auto p-4 sm:p-6">
            {error ? (
              <pre className="whitespace-pre-wrap rounded-md border border-destructive/30 bg-destructive/10 p-4 font-mono text-sm leading-6 text-destructive">
                {error}
              </pre>
            ) : preview ? (
              <div
                className="typst-preview mx-auto w-fit max-w-full"
                dangerouslySetInnerHTML={{ __html: preview }}
              />
            ) : (
              <div className="grid h-full min-h-80 place-items-center rounded-md border border-dashed border-border bg-background text-sm text-muted-foreground">
                Preparing compiler
              </div>
            )}
          </div>

          {isDragging ? (
            <div className="absolute inset-3 grid place-items-center rounded-md border-2 border-dashed border-primary bg-primary/10 text-sm font-medium text-primary">
              Drop a .typ file to open it
            </div>
          ) : null}
        </section>
      </section>
    </main>
  )
}
